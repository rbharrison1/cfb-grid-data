"""Generates every derived team-reference file from team_data/teams.json,
the single canonical source for team name/alias/id/color data.

To add, rename, or fix a team: edit teams.json directly, or use edit.py's
subcommands (recommended -- see README.md), then run this script and review
the diffs it produces across all 3 repos before committing/deploying each
one per its own normal process.

Usage:
    python team_data/generate.py [--web-repo PATH] [--check]

--web-repo PATH   Path to the cfb-grid-web checkout. Defaults to the sibling
                  directory this workspace already uses
                  (../../cfb-grid-web relative to this repo's root). If that
                  default doesn't exist and --web-repo isn't given, the
                  cfb-grid-web output is skipped with a warning rather than
                  failing -- the two cfb-grid-data-internal outputs stay
                  regenerable standalone.
--check           Dry run: compute every output in memory, diff against
                  what's on disk, print unified diffs, and exit non-zero if
                  anything would change. Also re-asserts the coverage
                  invariant (see _check_invariant below).
"""

import argparse
import difflib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)  # cfb-grid-data/cfb-grid-data/
TEAMS_JSON = os.path.join(HERE, 'teams.json')
DEFAULT_WEB_REPO = os.path.join(REPO_ROOT, '..', '..', 'cfb-grid-web')
TEAMS_LOOKUP_JSON_REL = os.path.join('mern', 'client', 'public', 'teams_lookup.json')

GENERATED_BANNER = '''"""GENERATED FILE -- do not hand-edit.

Generated by cfb-grid-data/cfb-grid-data/team_data/generate.py from
cfb-grid-data/cfb-grid-data/team_data/teams.json (copied alongside this file
as teams.json). To add, rename, or fix a team, edit team_data/teams.json (or
use team_data/edit.py) at the repo root and re-run
`python team_data/generate.py`, then review the diff before committing. See
team_data/README.md.
{extra}"""

import json
import os

with open(os.path.join(os.path.dirname(__file__), 'teams.json'), encoding='utf-8') as f:
    _TEAMS = json.load(f)

TEAM_NAME_SUBSTITUTIONS = {{
    name: team['canonical_name']
    for team in _TEAMS
    for name in [team['canonical_name'], *team['aliases']]
}}
TEAM_COLORS = {{team['canonical_name']: team['color'] for team in _TEAMS}}
'''

TRANSFORM_EXTRA_DOCSTRING = ''
LIVE_SCORES_EXTRA_DOCSTRING = '''
Used here as the first fallback tier when resolving an NCAA scoreboard team
name to the display name already stored in Mongo's away_team/home_team
fields (see team_match.py) -- Mongo's stored names are CFBD names already
run through this same substitution table, so this maps NCAA's raw name into
that same display-name space before falling back to NCAA_NAME_ALIASES.
'''


def load_teams():
    with open(TEAMS_JSON, encoding='utf-8') as f:
        return json.load(f)


def check_invariant(teams):
    """Every alias/canonical name must be unique across the whole file, and
    canonical_name must not be blank. Returns a list of problem strings
    (empty if clean)."""
    problems = []
    seen = {}
    for t in teams:
        if not t.get('canonical_name'):
            problems.append(f"team with espn_id={t.get('espn_id')} has no canonical_name")
        names = [t['canonical_name'], *t.get('aliases', [])]
        for n in names:
            if n in seen and seen[n] != t['espn_id']:
                problems.append(
                    f"name {n!r} claimed by both espn_id={seen[n]} and espn_id={t['espn_id']}"
                )
            seen[n] = t['espn_id']
    return problems


def render_teams_py(extra_docstring):
    return GENERATED_BANNER.format(extra=extra_docstring)


def render_teams_lookup_json(teams):
    flat = {}
    for t in teams:
        entry = {'id': str(t['espn_id']), 'color': t['color']}
        for name in [t['canonical_name'], *t['aliases']]:
            flat[name] = entry
    return json.dumps(flat, indent=2, ensure_ascii=False, sort_keys=True) + '\n'


def render_teams_json(teams):
    return json.dumps(teams, indent=2, ensure_ascii=False) + '\n'


def write_or_check(path, content, check, results):
    exists = os.path.isfile(path)
    current = None
    if exists:
        with open(path, encoding='utf-8') as f:
            current = f.read()

    if check:
        if current == content:
            results.append((path, None))
        else:
            diff = ''.join(difflib.unified_diff(
                (current or '').splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=path, tofile=path + ' (generated)',
            ))
            results.append((path, diff or '(new file)'))
    else:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        results.append((path, None))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--web-repo', default=DEFAULT_WEB_REPO)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()

    teams = load_teams()

    problems = check_invariant(teams)
    if problems:
        print('ERROR: teams.json failed its invariant check:', file=sys.stderr)
        for p in problems:
            print(f'  - {p}', file=sys.stderr)
        sys.exit(1)

    teams_json_content = render_teams_json(teams)
    transform_teams_py = render_teams_py(TRANSFORM_EXTRA_DOCSTRING)
    live_scores_teams_py = render_teams_py(LIVE_SCORES_EXTRA_DOCSTRING)
    teams_lookup_json_content = render_teams_lookup_json(teams)

    results = []
    write_or_check(os.path.join(REPO_ROOT, 'transform', 'config', 'teams.json'), teams_json_content, args.check, results)
    write_or_check(os.path.join(REPO_ROOT, 'transform', 'config', 'teams.py'), transform_teams_py, args.check, results)
    write_or_check(os.path.join(REPO_ROOT, 'live-scores', 'config', 'teams.json'), teams_json_content, args.check, results)
    write_or_check(os.path.join(REPO_ROOT, 'live-scores', 'config', 'teams.py'), live_scores_teams_py, args.check, results)

    web_repo = os.path.abspath(args.web_repo)
    teams_lookup_json_path = os.path.join(web_repo, TEAMS_LOOKUP_JSON_REL)
    if os.path.isdir(os.path.dirname(teams_lookup_json_path)):
        write_or_check(teams_lookup_json_path, teams_lookup_json_content, args.check, results)
    else:
        print(f'WARNING: {os.path.dirname(teams_lookup_json_path)} not found, skipping cfb-grid-web output '
              f'(pass --web-repo to point at your cfb-grid-web checkout)', file=sys.stderr)

    if args.check:
        changed = [(p, d) for p, d in results if d is not None]
        for path, diff in results:
            status = 'OK (matches disk)' if diff is None else 'WOULD CHANGE'
            print(f'{status}: {path}')
        if changed:
            print(f'\n{len(changed)} file(s) would change:\n')
            for path, diff in changed:
                print(diff)
            sys.exit(1)
        print('\nAll generated outputs match what is on disk.')
    else:
        for path, _ in results:
            print(f'Wrote {path}')


if __name__ == '__main__':
    main()
